export type TranslationKey = keyof typeof translations['es-PE'];

export function t(key: TranslationKey, locale: string = 'es-PE'): string {
  const loc = (locale === 'en-US' ? 'en-US' : 'es-PE') as Locale;
  return translations[loc][key] || translations['es-PE'][key] || key;
}

export function getGreeting(locale: string = 'es-PE', now: Date = new Date()): string {
  const loc = (locale === 'en-US' ? 'en-US' : 'es-PE') as Locale;
  const hour = now.getHours();

  if (hour < 12) {
    return t('greetingMorning', loc);
  }
  if (hour < 20) {
    return t('greetingAfternoon', loc);
  }
  return t('greetingEvening', loc);
}
